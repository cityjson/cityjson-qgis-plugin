import os

from qgis.PyQt import QtWidgets, uic
from qgis.gui import QgsExtentWidget, QgsFileWidget

FORM_CLASS, _ = uic.loadUiType(
    os.path.join(os.path.dirname(__file__), "cityjson_writer_dialog_base.ui")
)


class CityJsonWriterDialog(QtWidgets.QDialog, FORM_CLASS):
    def __init__(self, parent=None):
        """Constructor."""
        super(CityJsonWriterDialog, self).__init__(parent)
        self.setupUi(self)
        self.save_file_name.setStorageMode(
            QgsFileWidget.StorageMode.SaveFile
        )  # "save as", not "open"
        self.extent = QgsExtentWidget(self, QgsExtentWidget.WidgetStyle.CondensedStyle)
        self.extent.setNullValueAllowed(True, "Whole file")
        self.extent.toggleDialogVisibility.connect(
            self.setVisible
        )  # hide dialog while drawing on map
        self.verticalLayout_2.addWidget(
            QtWidgets.QLabel("Only export objects inside (optional):")
        )
        self.verticalLayout_2.addWidget(self.extent)

    def reset_fields(self):
        """Reset the fields in the dialog."""
        self.layer_select.clear()
        self.save_file_name.setFilePath("")
        self.keep_unloaded.setChecked(True)
        self.extent.clear()
